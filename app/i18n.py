def get_locale():
    # Priority: explicit session selection → Accept-Language → default language.
    lang = session.get("lang")
    if lang in current_app.config.get("SUPPORTED_LANGS", ()):
        return lang
    accept = request.accept_languages.best_match(current_app.config.get("SUPPORTED_LANGS"))
    return accept or current_app.config.get("DEFAULT_LANG", "ar")


def t(key: str) -> str:
    lang = getattr(g, "locale", current_app.config.get("DEFAULT_LANG", "ar"))
    return TRANSLATIONS.get(lang, {}).get(key) or TRANSLATIONS["en"].get(key) or key


def inject_i18n(app):
    @app.before_request
    def _set_locale():
        g.locale = get_locale()
        g.is_rtl = g.locale in RTL_LANGS

    @app.context_processor
    def _ctx():
        return {
            "t": t,
            "locale": getattr(g, "locale", app.config.get("DEFAULT_LANG", "ar")),
            "is_rtl": getattr(g, "is_rtl", True),
            "supported_langs": app.config.get("SUPPORTED_LANGS", ("ar", "en", "ku")),
            "rtl_langs": RTL_LANGS,
        }
